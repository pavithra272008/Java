CREATE TABLE beach_sectors (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL UNIQUE,
    location VARCHAR(250),
    active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE water_samples (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sector_id BIGINT NOT NULL REFERENCES beach_sectors(id),
    collected_at TIMESTAMP WITH TIME ZONE NOT NULL,
    bacteria_count DOUBLE PRECISION NOT NULL CHECK (bacteria_count >= 0),
    safety_threshold DOUBLE PRECISION NOT NULL CHECK (safety_threshold > 0),
    risk_level VARCHAR(20) NOT NULL CHECK (risk_level IN ('GREEN', 'RED'))
);

CREATE INDEX idx_water_samples_sector_collected
    ON water_samples (sector_id, collected_at DESC);
