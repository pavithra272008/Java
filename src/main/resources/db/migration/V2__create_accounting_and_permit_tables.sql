-- Chart of Accounts Master
CREATE TABLE accounts (
    code VARCHAR(20) PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    type VARCHAR(30) NOT NULL CHECK (type IN ('ASSET', 'LIABILITY', 'INCOME', 'EXPENSE')),
    balance NUMERIC(15,2) NOT NULL DEFAULT 0.00
);

-- Contact Master (Beach Event Organizers, Testing Laboratories, Safety Equipment Vendors)
CREATE TABLE contacts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    type VARCHAR(30) NOT NULL CHECK (type IN ('CUSTOMER', 'VENDOR')),
    email VARCHAR(150),
    phone VARCHAR(50),
    tax_id VARCHAR(50)
);

-- Product Master (Permits, Testing Services, Rescue Goods)
CREATE TABLE products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    type VARCHAR(30) NOT NULL CHECK (type IN ('SERVICE', 'GOODS')),
    price NUMERIC(12,2) NOT NULL,
    description VARCHAR(250),
    account_code VARCHAR(20) REFERENCES accounts(code)
);

-- Purchase Orders (Weekly lab testing POs, Rescue equipment)
CREATE TABLE purchase_orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    po_number VARCHAR(50) NOT NULL UNIQUE,
    vendor_id BIGINT NOT NULL REFERENCES contacts(id),
    order_date DATE NOT NULL,
    status VARCHAR(30) NOT NULL CHECK (status IN ('DRAFT', 'CONFIRMED', 'BILLED', 'CANCELLED')),
    total_amount NUMERIC(12,2) NOT NULL,
    description VARCHAR(250)
);

-- Sales Orders (Commercial Beach Event Permits)
CREATE TABLE sales_orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_number VARCHAR(50) NOT NULL UNIQUE,
    customer_id BIGINT NOT NULL REFERENCES contacts(id),
    sector_id BIGINT REFERENCES beach_sectors(id),
    order_date DATE NOT NULL,
    status VARCHAR(30) NOT NULL CHECK (status IN ('DRAFT', 'CONFIRMED', 'INVOICED', 'CANCELLED')),
    total_amount NUMERIC(12,2) NOT NULL,
    description VARCHAR(250)
);

-- Invoices & Vendor Bills
CREATE TABLE invoices (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_number VARCHAR(50) NOT NULL UNIQUE,
    type VARCHAR(30) NOT NULL CHECK (type IN ('CUSTOMER_INVOICE', 'VENDOR_BILL')),
    contact_id BIGINT NOT NULL REFERENCES contacts(id),
    source_order_ref VARCHAR(50),
    invoice_date DATE NOT NULL,
    due_date DATE NOT NULL,
    status VARCHAR(30) NOT NULL CHECK (status IN ('POSTED', 'PAID', 'CANCELLED')),
    amount NUMERIC(12,2) NOT NULL,
    amount_paid NUMERIC(12,2) NOT NULL DEFAULT 0.00
);

-- Payments (Paid via Bank)
CREATE TABLE payments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_reference VARCHAR(50) NOT NULL UNIQUE,
    invoice_id BIGINT NOT NULL REFERENCES invoices(id),
    payment_date DATE NOT NULL,
    amount NUMERIC(12,2) NOT NULL,
    payment_method VARCHAR(30) NOT NULL CHECK (payment_method IN ('BANK_TRANSFER', 'CASH'))
);

-- Journal Entries (General Ledger)
CREATE TABLE journal_entries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entry_number VARCHAR(50) NOT NULL UNIQUE,
    entry_date DATE NOT NULL,
    journal_type VARCHAR(30) NOT NULL CHECK (journal_type IN ('SALES', 'PURCHASE', 'CASH', 'BANK')),
    reference VARCHAR(50),
    description VARCHAR(250),
    debit_account_code VARCHAR(20) NOT NULL REFERENCES accounts(code),
    credit_account_code VARCHAR(20) NOT NULL REFERENCES accounts(code),
    amount NUMERIC(12,2) NOT NULL
);

CREATE INDEX idx_po_vendor ON purchase_orders(vendor_id);
CREATE INDEX idx_so_customer ON sales_orders(customer_id);
CREATE INDEX idx_invoice_contact ON invoices(contact_id);
CREATE INDEX idx_journal_date ON journal_entries(entry_date);
